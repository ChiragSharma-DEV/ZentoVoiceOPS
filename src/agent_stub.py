from __future__ import annotations

from typing import Any
from src.agent_protocol import Agent


class StubAgent:
    """STUB Agent implementation strictly for plumbing and pipeline verification."""

    def __init__(self, name: str = "STUB") -> None:
        self.name = name

    def respond(self, customer_text: str, language_code: str) -> dict[str, Any]:
        """Respond with a canned [STUB] message.

        Contains no ZentroMart answers.
        """
        cleaned_text = (customer_text or "").strip()
        if not cleaned_text:
            return {
                "reply": "[STUB] No customer input was provided. Please clarify your request.",
                "decision": "clarify",
                "used_sections": ["STUB-NONE"],
            }

        # Safe stub response echoing the cleaned input without domain answering
        truncated_preview = cleaned_text[:80] + ("..." if len(cleaned_text) > 80 else "")
        return {
            "reply": f"[STUB] Echo acknowledged in {language_code}: '{truncated_preview}'. Stub pipeline active.",
            "decision": "answer",
            "used_sections": ["STUB-PLUMBING-01"],
        }


